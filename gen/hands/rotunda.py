"""Blackletter: Rotunda (the Italian and Spanish round gothic book hand).

Measured on the teaching sheet "La gothique rotunda" (a French exemplar with numbered ductus, after the Bologna bible
of 1267; its notes: x-height 4 nib widths, the pen held almost parallel to the line, up to 30° in some letters;
capitals built on 5 1/2 nib widths), in its pixels:

  x-height                    34 px (4 nib widths)        stem                     7-9 px (0.94 of the nib)
  nib                         8.5 px                      nib angle                20-30° (stems nearly the whole nib);
                                                          set at 30°, the sheet's upper bound: the hairlines and the
                                                          heavy flat strokes of the bowls need it
  ascender b, d, h, k, l      1.3-1.35 x-heights          descender p, q 0.37; g 0.45; y's hairline 0.65
  capitals                    1.375 (5 1/2 : 4 nib widths); flourished tops to 1.45; I, J, Y descend 0.3
  slant                       0° (stems measured vertical)
  widths (ink / x-height)     n 0.94, o 1.06, m 1.47, b 1.06, d 1.06, a 0.88; capitals 1.6-1.9 (A, C, D, H, M)

Small letters: wide and round, with short extenders; stems are cut square at the top (a short hairline lead-in) and
stand flat on the line or turn up to the right (l, t, u); bowls are round with a slight break at the top and bottom,
not the Textura's lozenge; the a is the Rotunda a, a stem with a curl at its head and a small diamond bowl closed by a
hairline; d is upright; r is the standard r with a diamond flag (the 2-shaped r used after round letters is not
needed here); the round s is wide, with a diamond on its spine; x and y have hairline descenders. Capitals are the
sheet's: wide, with a short lead-in tick at the left, doubled stems and a diagonal hairline through the bowl (the
hairline doubling is written as one hairline; two close parallel lines cannot be told apart at this size). j, v, w and
the figures are not on the sheet and are written as Rotunda scribes wrote them: j as an i with a curved descender, v
and w with the round right side of b, figures round and lining (1.1 x-heights). The unit is the x-height.
"""
from gen.pen import bez, chain, line


def lead(u, top=1.0):
    """the hairline lead-in at the head of a stem"""
    return line((u - 0.12, top - 0.09), (u, top))


def stem(u, top=1.0, bot=0.02, lead_in=True):
    s = line((u, top), (u, bot))
    return chain(lead(u, top), s) if lead_in else s


def turn(u, bot=0.2, reach=0.3):
    """a stem that turns up to the right at the line (l, t, u)"""
    return bez((u, bot), (u, 0.0), (u + reach * 0.55, -0.01), (u + reach, 0.12))


def arch(u, w):
    """the round arch of n, m, h: out of the stem at u, over and down the next stem at u + w"""
    return chain(bez((u + 0.03, 0.86), (u + 0.12, 0.98), (u + w - 0.18, 1.04), (u + w, 0.9)), line((u + w, 0.9), (u + w, 0.02)))


def bowl_left(u0, top=(0.0, 0.98), w=0.42):
    """the round left side of c, d, e, o, q: from the top over to the left and round to the bottom"""
    x, y = top
    return bez((x, y), (x - w, y - 0.02), (x - w, 0.04), (x - 0.04, 0.0))


